/**
 * @file
 *
 * The policy gcert_x509_path applies on top of RFC 5280's algorithm, and the
 * rules it already applied that nothing tested.
 *
 * Every one of these was a mutation that survived `make test` on 2026-09-28:
 * pathLenConstraint, the keyCertSign requirement, and the signature-algorithm
 * to issuer-key match. The rest - weak digests, small keys, an expired
 * anchor, extendedKeyUsage - are rules added because the audit found the
 * chain validating without them.
 *
 * The instant each test validates at is read from the certificates rather
 * than hardcoded, so a fixture regenerated by tools/make-fixtures.sh does not
 * expire and does not have to be regenerated in step with the tests.
 *
 * Copyright 2026 by Corey Pennycuff
 */

#include "test_helpers.h"

#include <cstdint>
#include <cstring>
#include <string>
#include <fstream>
#include <vector>

namespace {

std::vector<unsigned char> load(const char * name) {
  std::ifstream in(gsectest::data_dir() + "/certs/" + name, std::ios::binary);
  EXPECT_TRUE(in.good()) << name;
  return std::vector<unsigned char>(std::istreambuf_iterator<char>(in),
      std::istreambuf_iterator<char>());
}

/* An instant inside both certificates' validity periods. */
int64_t both_valid(const std::vector<unsigned char> & a,
    const std::vector<unsigned char> & b) {
  GCERT_X509 pa;
  GCERT_X509 pb;
  EXPECT_EQ(gcert_x509_parse(a.data(), a.size(), &pa), GCERT_OK);
  EXPECT_EQ(gcert_x509_parse(b.data(), b.size(), &pb), GCERT_OK);
  int64_t from = pa.not_before > pb.not_before ? pa.not_before : pb.not_before;
  int64_t to = pa.not_after < pb.not_after ? pa.not_after : pb.not_after;
  return from + (to - from) / 2;
}

GCERT_Result path(const std::vector<unsigned char> & leaf,
    const std::vector<unsigned char> & anchor, int64_t when,
    unsigned purpose = 0) {
  return gcert_x509_path(leaf.data(), leaf.size(), nullptr, nullptr, 0,
      anchor.data(), anchor.size(), when, purpose);
}

GCERT_Result path_mid(const std::vector<unsigned char> & leaf,
    const std::vector<unsigned char> & mid,
    const std::vector<unsigned char> & anchor, int64_t when) {
  const void * mids[1] = {mid.data()};
  size_t lens[1] = {mid.size()};
  return gcert_x509_path(leaf.data(), leaf.size(), mids, lens, 1, anchor.data(),
      anchor.size(), when, 0);
}

} /* namespace */

/* --- Weak digests ------------------------------------------------------- */

TEST(X509Policy, Sha1ChainIsRefusedButStillVerifies) {
  auto ca = load("sha1-ca.der");
  auto leaf = load("sha1-leaf.der");
  GCERT_X509 pl;
  GCERT_X509 pc;
  ASSERT_EQ(gcert_x509_parse(leaf.data(), leaf.size(), &pl), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(ca.data(), ca.size(), &pc), GCERT_OK);
  EXPECT_EQ(pl.sig_hash, GSEC_RSA_SHA1);
  /* The signature is real: this is how a caller identifies an old
   * certificate. What it must not do is pass for a valid chain. */
  EXPECT_EQ(gcert_x509_signed_by(&pl, &pc), GCERT_OK);
  EXPECT_EQ(path(leaf, ca, both_valid(leaf, ca)), GCERT_ERR_UNSUPPORTED);
}

TEST(X509Policy, Md5ChainIsRefusedButStillVerifies) {
  auto ca = load("md5-ca.der");
  auto leaf = load("md5-leaf.der");
  GCERT_X509 pl;
  GCERT_X509 pc;
  ASSERT_EQ(gcert_x509_parse(leaf.data(), leaf.size(), &pl), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(ca.data(), ca.size(), &pc), GCERT_OK);
  EXPECT_EQ(pl.sig_hash, GSEC_RSA_MD5);
  EXPECT_EQ(gcert_x509_signed_by(&pl, &pc), GCERT_OK);
  EXPECT_EQ(path(leaf, ca, both_valid(leaf, ca)), GCERT_ERR_UNSUPPORTED);
}

/* --- Key size ----------------------------------------------------------- */

TEST(X509Policy, SmallRsaKeyIsRefused) {
  auto ca = load("weakkey-ca.der");
  auto leaf = load("weakkey-leaf.der");
  GCERT_X509 pl;
  ASSERT_EQ(gcert_x509_parse(leaf.data(), leaf.size(), &pl), GCERT_OK);
  EXPECT_EQ(pl.key, GCERT_X509_RSA);
  EXPECT_LT(pl.n_len * 8u, GCERT_X509_RSA_MIN_BITS);
  EXPECT_EQ(path(leaf, ca, both_valid(leaf, ca)), GCERT_ERR_UNSUPPORTED);
}

TEST(X509Policy, TwoThousandFortyEightBitKeyIsAccepted) {
  auto ca = load("sha1-ca.der");
  GCERT_X509 pc;
  ASSERT_EQ(gcert_x509_parse(ca.data(), ca.size(), &pc), GCERT_OK);
  /* The control for the test above: the same generator, the same shape, a
   * key that clears the floor. Only the digest makes that chain fail. */
  EXPECT_GE(pc.n_len * 8u, GCERT_X509_RSA_MIN_BITS);
}

/* --- The anchor's own validity ------------------------------------------ */

TEST(X509Policy, ExpiredAnchorIsRefused) {
  auto ca = load("shortca-ca.der");
  auto leaf = load("shortca-leaf.der");
  GCERT_X509 pc;
  GCERT_X509 pl;
  ASSERT_EQ(gcert_x509_parse(ca.data(), ca.size(), &pc), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(leaf.data(), leaf.size(), &pl), GCERT_OK);
  /* The anchor is good for two days and the leaf for ten years, so there is
   * an instant where only the anchor has expired. RFC 5280 section 6.1 does
   * not examine the anchor's dates; this library does. */
  int64_t after_ca = pc.not_after + 1;
  ASSERT_LT(after_ca, pl.not_after);
  ASSERT_GT(after_ca, pl.not_before);
  EXPECT_EQ(path(leaf, ca, after_ca), GCERT_ERR_MISMATCH);
  EXPECT_EQ(path(leaf, ca, pc.not_after), GCERT_OK);
}

/* --- extendedKeyUsage --------------------------------------------------- */

TEST(X509Policy, EkuIsParsedAndNotDiscarded) {
  auto server = load("eku-server.der");
  auto code = load("eku-code.der");
  auto any = load("eku-any.der");
  auto both = load("eku-both.der");
  auto unknown = load("eku-unknown.der");
  GCERT_X509 p;

  ASSERT_EQ(gcert_x509_parse(server.data(), server.size(), &p), GCERT_OK);
  EXPECT_EQ(p.eku_set, 1);
  EXPECT_EQ(p.eku, GCERT_X509_EKU_SERVER_AUTH);
  EXPECT_EQ(p.eku_critical, 0);
  EXPECT_EQ(p.eku_unknown, 0);

  ASSERT_EQ(gcert_x509_parse(code.data(), code.size(), &p), GCERT_OK);
  EXPECT_EQ(p.eku, GCERT_X509_EKU_CODE_SIGNING);
  EXPECT_EQ(p.eku_critical, 1);

  ASSERT_EQ(gcert_x509_parse(any.data(), any.size(), &p), GCERT_OK);
  EXPECT_EQ(p.eku, GCERT_X509_EKU_ANY);

  ASSERT_EQ(gcert_x509_parse(both.data(), both.size(), &p), GCERT_OK);
  EXPECT_EQ(p.eku,
      GCERT_X509_EKU_SERVER_AUTH | GCERT_X509_EKU_CLIENT_AUTH);

  ASSERT_EQ(gcert_x509_parse(unknown.data(), unknown.size(), &p), GCERT_OK);
  EXPECT_EQ(p.eku_set, 1);
  EXPECT_EQ(p.eku, 0u);
  EXPECT_EQ(p.eku_unknown, 1);
}

TEST(X509Policy, PurposeIsEnforcedWhenAsked) {
  auto server = load("eku-server.der");
  auto code = load("eku-code.der");
  auto any = load("eku-any.der");
  auto unknown = load("eku-unknown.der");
  auto plain = load("p256-leaf.der");
  GCERT_X509 ps;
  GCERT_X509 pc;
  GCERT_X509 pa;
  GCERT_X509 pu;
  GCERT_X509 pp;
  ASSERT_EQ(gcert_x509_parse(server.data(), server.size(), &ps), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(code.data(), code.size(), &pc), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(any.data(), any.size(), &pa), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(unknown.data(), unknown.size(), &pu), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(plain.data(), plain.size(), &pp), GCERT_OK);

  EXPECT_EQ(gcert_x509_purpose(&ps, GCERT_X509_EKU_SERVER_AUTH), GCERT_OK);
  EXPECT_EQ(gcert_x509_purpose(&ps, GCERT_X509_EKU_CODE_SIGNING),
      GCERT_ERR_MISMATCH);
  /* The case the audit named: a certificate issued for code signing, marked
   * critical, must not pass as a TLS server certificate. */
  EXPECT_EQ(gcert_x509_purpose(&pc, GCERT_X509_EKU_SERVER_AUTH),
      GCERT_ERR_MISMATCH);
  EXPECT_EQ(gcert_x509_purpose(&pa, GCERT_X509_EKU_SERVER_AUTH), GCERT_OK);
  /* Purposes this parser has no bit for are not a licence. */
  EXPECT_EQ(gcert_x509_purpose(&pu, GCERT_X509_EKU_SERVER_AUTH),
      GCERT_ERR_MISMATCH);
  /* No extension at all permits everything, which is RFC 5280. */
  EXPECT_EQ(gcert_x509_purpose(&pp, GCERT_X509_EKU_SERVER_AUTH), GCERT_OK);
  EXPECT_EQ(gcert_x509_purpose(nullptr, GCERT_X509_EKU_SERVER_AUTH),
      GCERT_ERR_INVALID);
  EXPECT_EQ(gcert_x509_purpose(&ps, 0), GCERT_ERR_INVALID);
}

TEST(X509Policy, PathChecksThePurposeItIsGiven) {
  auto ca = load("sha1-ca.der");
  auto code = load("eku-code.der");
  /* eku-code.der is self-signed, so it is its own anchor: this isolates the
   * purpose check from every other rule. */
  int64_t when = both_valid(code, code);
  EXPECT_EQ(path(code, code, when, 0), GCERT_OK);
  EXPECT_EQ(path(code, code, when, GCERT_X509_EKU_CODE_SIGNING), GCERT_OK);
  EXPECT_EQ(path(code, code, when, GCERT_X509_EKU_SERVER_AUTH),
      GCERT_ERR_MISMATCH);
  (void)ca;
}

/* --- pathLenConstraint -------------------------------------------------- */

TEST(X509Policy, PathLenZeroRefusesAnIntermediate) {
  auto ca = load("plen-ca.der");
  auto mid = load("plen-mid.der");
  auto leaf = load("plen-leaf.der");
  auto direct = load("plen-direct.der");
  GCERT_X509 pc;
  ASSERT_EQ(gcert_x509_parse(ca.data(), ca.size(), &pc), GCERT_OK);
  EXPECT_EQ(pc.path_len_set, 1);
  EXPECT_EQ(pc.path_len, 0u);
  int64_t when = both_valid(leaf, ca);
  /* pathlen:0 permits end-entity certificates and no further CA. */
  EXPECT_EQ(path(direct, ca, when), GCERT_OK);
  EXPECT_EQ(path_mid(leaf, mid, ca, when), GCERT_ERR_MISMATCH);
}

/* --- keyCertSign -------------------------------------------------------- */

TEST(X509Policy, IntermediateWithoutKeyCertSignIsRefused) {
  auto ca = load("nokcs-ca.der");
  auto mid = load("nokcs-mid.der");
  auto leaf = load("nokcs-leaf.der");
  GCERT_X509 pm;
  ASSERT_EQ(gcert_x509_parse(mid.data(), mid.size(), &pm), GCERT_OK);
  EXPECT_EQ(pm.ca, 1);
  EXPECT_EQ(pm.key_usage_set, 1);
  EXPECT_EQ(pm.key_usage & 0x04u, 0u);
  EXPECT_EQ(path_mid(leaf, mid, ca, both_valid(leaf, ca)), GCERT_ERR_MISMATCH);
}

/* --- The signature algorithm must match the issuer's key ---------------- */

TEST(X509Policy, SignatureAlgorithmMustMatchIssuerKey) {
  auto rsa_leaf = load("rsa-leaf.der");
  auto p256_ca = load("p256-ca.der");
  GCERT_X509 pl;
  GCERT_X509 pc;
  ASSERT_EQ(gcert_x509_parse(rsa_leaf.data(), rsa_leaf.size(), &pl), GCERT_OK);
  ASSERT_EQ(gcert_x509_parse(p256_ca.data(), p256_ca.size(), &pc), GCERT_OK);
  EXPECT_EQ(pl.sig_key, GCERT_X509_RSA);
  EXPECT_EQ(pc.key, GCERT_X509_P256);
  /* An RSA signature offered to an EC key is refused before any verification
   * is attempted, rather than dispatched on the issuer's key type. */
  EXPECT_EQ(gcert_x509_signed_by(&pl, &pc), GCERT_ERR_MISMATCH);
}

/* --- The hostname matcher's refusals -------------------------------------- */

TEST(X509Policy, WildcardPatternsThatMustNotMatch) {
  /* The audit found these untested: replacing every `return 0` in host_match
   * with `return 1` left the suite passing, because the three negative cases
   * that existed all fail on the final byte comparison instead. A CA would
   * not issue these names; that is not a reason for the matcher to accept
   * them. Each host below is one that would match if the rule being tested
   * were removed. */
  struct Case {
    const char * fixture;
    const char * host;
  };
  const Case refused[] = {
    /* A `*` that is not the whole leading label is not a wildcard. */
    {"san-wild-mid.der", "www.example.com"},
    {"san-wild-mid.der", "w*w.example.com"},
    /* Two wildcards: the second is not special, and the first covers one
     * label only. */
    {"san-wild-two.der", "a.b.example.com"},
    {"san-wild-inner.der", "www.any.example.com"},
    /* A bare `*` is not a pattern that matches everything. */
    {"san-bare-wild.der", "example"},
  };
  for (const Case & c : refused) {
    auto der = load(c.fixture);
    GCERT_X509 parsed;
    ASSERT_EQ(gcert_x509_parse(der.data(), der.size(), &parsed), GCERT_OK)
        << c.fixture;
    EXPECT_EQ(gcert_x509_hostname(&parsed, c.host, std::strlen(c.host)),
        GCERT_ERR_MISMATCH) << c.fixture << " matched " << c.host;
  }

  /* `host_ok` is applied to the pattern as well, and that arm cannot be
   * reached with a distinguishing input: the same malformed name offered as
   * the host is refused first, below, so a pattern-side rejection never
   * decides an answer on its own. Noted rather than tested, because a test
   * that cannot fail is worse than none. */
}

TEST(X509Policy, WildcardTldStillMatchesOneLabel) {
  /* Recorded rather than endorsed: `*.com` matches `example.com` here,
   * because this matcher applies no minimum label count. No CA issues such a
   * name. If that policy changes, this is the test to change with it. */
  auto der = load("san-wild-tld.der");
  GCERT_X509 parsed;
  ASSERT_EQ(gcert_x509_parse(der.data(), der.size(), &parsed), GCERT_OK);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "example.com", 11), GCERT_OK);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "a.example.com", 13),
      GCERT_ERR_MISMATCH);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "com", 3), GCERT_ERR_MISMATCH);
}

TEST(X509Policy, HostNamesThatAreNotNames) {
  /* A malformed name from the caller is GCERT_ERR_INVALID, not a mismatch:
   * the question was not asked properly. A trailing dot is the exception -
   * it is the absolute form of the same name and is stripped. */
  auto der = load("p256-leaf.der");
  GCERT_X509 parsed;
  ASSERT_EQ(gcert_x509_parse(der.data(), der.size(), &parsed), GCERT_OK);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "www.example.com", 15), GCERT_OK);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "www.example.com.", 16), GCERT_OK);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "WWW.Example.COM.", 16), GCERT_OK);

  EXPECT_EQ(gcert_x509_hostname(&parsed, "", 0), GCERT_ERR_INVALID);
  EXPECT_EQ(gcert_x509_hostname(&parsed, ".", 1), GCERT_ERR_INVALID);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "www..example.com", 16),
      GCERT_ERR_INVALID);
  EXPECT_EQ(gcert_x509_hostname(&parsed, "www.example.com\x01", 16),
      GCERT_ERR_INVALID);
  /* Two bytes of UTF-8 in the middle: 17 characters, not 19. Passing the
   * wrong length here was a one-byte over-read of the literal, which is what
   * `make test-asan` reported - in the test, not the library. */
  EXPECT_EQ(gcert_x509_hostname(&parsed, "www.exam\xc3\xa9ple.com", 17),
      GCERT_ERR_INVALID);
  {
    /* Longer than 253 bytes, and a single label longer than 63. */
    std::string long_name(254, 'a');
    EXPECT_EQ(gcert_x509_hostname(&parsed, long_name.c_str(),
        long_name.size()), GCERT_ERR_INVALID);
    std::string long_label(64, 'a');
    long_label += ".example.com";
    EXPECT_EQ(gcert_x509_hostname(&parsed, long_label.c_str(),
        long_label.size()), GCERT_ERR_INVALID);
  }
  {
    /* An embedded NUL, which is the classic way a name in a certificate is
     * made to read as one thing to this library and another to a C caller. */
    const char embedded[] = "www.example.com\0.evil.example";
    EXPECT_EQ(gcert_x509_hostname(&parsed, embedded, sizeof embedded - 1u),
        GCERT_ERR_INVALID);
  }
  EXPECT_EQ(gcert_x509_hostname(&parsed, nullptr, 1), GCERT_ERR_INVALID);
  EXPECT_EQ(gcert_x509_hostname(nullptr, "a", 1), GCERT_ERR_INVALID);
}

