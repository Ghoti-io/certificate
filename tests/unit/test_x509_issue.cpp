TEST(X509Issue, FailureWipesTheBuffer) {
  unsigned char buf[64];
  size_t n = 99;
  GCERT_X509_Tbs tbs;
  GCERT_X509_Signer signer;
  unsigned char scalar[GSEC_ECDSA_P256_LEN];
  unsigned char point[GSEC_ECDSA_P256_PUBLIC_LEN];

  EXPECT_EQ(gcert_x509_issue(nullptr, nullptr, nullptr, sizeof buf, &n),
      GCERT_ERR_INVALID);
  EXPECT_EQ(n, 99u);

  std::memset(buf, 0xa5, sizeof buf);
  EXPECT_EQ(gcert_x509_issue(nullptr, nullptr, buf, sizeof buf, nullptr),
      GCERT_ERR_INVALID);
  expect_zeros(buf, sizeof buf);
  EXPECT_EQ(n, 99u);

  std::memset(buf, 0xa5, sizeof buf);
  std::memset(&tbs, 0, sizeof tbs);
  std::memset(&signer, 0, sizeof signer);
  EXPECT_EQ(gcert_x509_issue(&tbs, &signer, buf, sizeof buf, &n),
      GCERT_ERR_INVALID);
  expect_zeros(buf, sizeof buf);
  EXPECT_EQ(n, 99u);

  std::memset(scalar, 0, sizeof scalar);
  scalar[sizeof scalar - 1] = 1;
  ASSERT_EQ(gsec_ecdsa_p256_public(scalar, point), GSEC_OK);
  std::memset(&tbs, 0, sizeof tbs);
  std::memset(&signer, 0, sizeof signer);
  tbs.issuer = kName;
  tbs.issuer_len = sizeof kName;
  tbs.subject = kName;
  tbs.subject_len = sizeof kName;
  tbs.not_before = kNotBefore;
  tbs.not_after = kNotAfter;
  tbs.serial = scalar;
  tbs.serial_len = 1;
  tbs.subject_key = GCERT_X509_P256;
  tbs.point = point;
  tbs.point_len = sizeof point;
  signer.key = GCERT_X509_P256;
  signer.d = scalar;
  signer.d_len = sizeof scalar;
  std::memset(buf, 0xa5, sizeof buf);
  n = 99;
  EXPECT_EQ(gcert_x509_issue(&tbs, &signer, buf, sizeof buf, &n),
      GCERT_ERR_LIMIT);
  expect_zeros(buf, sizeof buf);
  EXPECT_EQ(n, 99u);
}

